"use server";

import { db } from "@/lib/db";
import { logEvent } from "@/lib/audit";
import { authorize } from "@/lib/auth/session";
import { getAIProvider, type CategorySuggestion } from "@/lib/ai/provider";
import { getUserMap } from "@/lib/data/lookups";
import { loadInvoices, loadPromises, sumBy } from "@/lib/data/receivables";
import { daysBetween, fmtDate } from "@/lib/dates";
import { CLOSED_ISSUE_STATUSES, ISSUE_CATEGORIES, ISSUE_STATUSES, labelOf } from "@/lib/domain/constants";
import { fmtINR } from "@/lib/format";

export type DraftState = { draft?: string; provider?: string; error?: string; at?: number } | null;

// AI failures are non-blocking: every action returns an error message instead of throwing.
async function safe(fn: () => Promise<DraftState>): Promise<DraftState> {
  try {
    return await fn();
  } catch (e) {
    console.error("[ai]", e instanceof Error ? e.message : e);
    return { error: "The assistant is unavailable right now. You can continue working without it." };
  }
}

export async function aiDraftFollowUp(invoiceId: string, _: DraftState): Promise<DraftState> {
  return safe(async () => {
    const user = await authorize("receivables:view");
    const [inv] = await loadInvoices(user, { ids: [invoiceId] });
    if (!inv) return { error: "Invoice not found." };
    const customer = await db.customer.findFirst({ where: { id: inv.customerId, orgId: user.orgId } });
    const promises = (await loadPromises(user, { invoiceId })).filter((p) => p.status !== "cancelled");
    const last = promises[0];
    const ai = getAIProvider();
    const draft = await ai.draftFollowUpEmail({
      orgName: user.org.name,
      customerName: inv.customerName,
      contactName: customer?.accountsContactName ?? "",
      invoiceNumber: inv.number,
      invoiceDate: fmtDate(inv.invoiceDate),
      dueDate: fmtDate(inv.dueDate),
      outstanding: fmtINR(inv.outstanding, true),
      overdueDays: inv.overdueDays ?? 0,
      openIssue: inv.openIssues[0] ? `${inv.openIssues[0].number} – ${labelOf(ISSUE_CATEGORIES, inv.openIssues[0].category)}` : undefined,
      lastPromise: last ? `on ${fmtDate(last.promisedDate)} (${fmtINR(last.amount)})` : undefined,
      senderName: user.name,
    });
    await logEvent(user, { entityType: "invoice", entityId: inv.id, customerId: inv.customerId, kind: "ai_draft", source: "system", message: `Follow-up email draft generated by ${ai.name} for review (not sent).` });
    return { draft, provider: ai.name, at: Date.now() };
  });
}

export async function aiSummarizeIssue(issueId: string, _: DraftState): Promise<DraftState> {
  return safe(async () => {
    const user = await authorize("issues:view");
    const is = await db.issue.findFirst({ where: { id: issueId, orgId: user.orgId } });
    if (!is) return { error: "Issue not found." };
    const [users, customer, invoice, order, events] = await Promise.all([
      getUserMap(user.orgId),
      db.customer.findFirst({ where: { id: is.customerId, orgId: user.orgId } }),
      is.invoiceId ? db.invoice.findFirst({ where: { id: is.invoiceId, orgId: user.orgId } }) : null,
      is.orderId ? db.salesOrder.findFirst({ where: { id: is.orderId, orgId: user.orgId } }) : null,
      db.activityEvent.findMany({ where: { orgId: user.orgId, entityType: "issue", entityId: is.id }, orderBy: { createdAt: "desc" }, take: 10 }),
    ]);
    const ai = getAIProvider();
    const draft = await ai.summarizeIssue({
      number: is.number, title: is.title, category: labelOf(ISSUE_CATEGORIES, is.category), status: labelOf(ISSUE_STATUSES, is.status),
      customerName: customer?.name ?? "—", createdOn: fmtDate(is.createdAt), ageDays: daysBetween(is.createdAt, user.today), description: is.description,
      owner: is.ownerId ? users.get(is.ownerId) ?? "—" : "Unassigned", missingEvidence: is.missingEvidence, nextAction: is.nextAction,
      linked: [invoice && `Invoice ${invoice.number}`, order && `Order ${order.number}`].filter(Boolean) as string[],
      events: events.map((e) => ({ when: fmtDate(e.createdAt), who: e.userId ? users.get(e.userId) ?? "Customer" : e.source, text: e.message })),
    });
    return { draft, provider: ai.name, at: Date.now() };
  });
}

export async function aiSummarizeCustomer(customerId: string, _: DraftState): Promise<DraftState> {
  return safe(async () => {
    const user = await authorize("customers:view");
    const c = await db.customer.findFirst({ where: { id: customerId, orgId: user.orgId } });
    if (!c) return { error: "Customer not found." };
    const [invoices, promises, issues, events] = await Promise.all([
      loadInvoices(user, { customerId }),
      loadPromises(user, { customerId }),
      db.issue.findMany({ where: { orgId: user.orgId, customerId, status: { notIn: CLOSED_ISSUE_STATUSES } } }),
      db.activityEvent.findMany({ where: { orgId: user.orgId, customerId, kind: { in: ["comment", "collection", "status_change", "promise", "created"] } }, orderBy: { createdAt: "desc" }, take: 8 }),
    ]);
    const open = invoices.filter((i) => i.outstanding > 0);
    const od = open.filter((i) => (i.overdueDays ?? 0) > 0);
    const ai = getAIProvider();
    const draft = await ai.summarizeCustomer({
      customerName: c.name,
      outstanding: fmtINR(sumBy(open, (i) => i.outstanding)),
      overdue: fmtINR(sumBy(od, (i) => i.outstanding)),
      openInvoices: open.length,
      overdueInvoices: od.length,
      openIssues: issues.map((i) => `${i.number} ${i.title}`),
      missedPromises: promises.filter((p) => p.status === "missed").length,
      recent: events.map((e) => ({ when: fmtDate(e.createdAt), text: e.message })),
    });
    return { draft, provider: ai.name, at: Date.now() };
  });
}

export async function aiSuggestCategories(notes: string): Promise<{ suggestions: CategorySuggestion[]; provider: string } | { error: string }> {
  try {
    await authorize("issues:edit");
    const text = String(notes ?? "").slice(0, 4000);
    const ai = getAIProvider();
    return { suggestions: await ai.suggestIssueCategories(text), provider: ai.name };
  } catch {
    return { error: "Suggestions unavailable." };
  }
}
