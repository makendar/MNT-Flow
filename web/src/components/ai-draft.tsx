"use client";

import { useActionState, useState } from "react";
import { Sparkles } from "lucide-react";
import type { DraftState } from "@/lib/actions/ai";
import { aiSuggestCategories } from "@/lib/actions/ai";

/** Generates an editable draft. Drafts are never sent or saved automatically. */
export function AiDraft({ title, description, action, buttonLabel }: { title: string; description: string; action: (prev: DraftState) => Promise<DraftState>; buttonLabel: string }) {
  const [state, run, pending] = useActionState(action, null);

  return (
    <section className="card">
      <div className="card-h">
        <h2 className="card-t flex items-center gap-1.5"><Sparkles className="h-4 w-4 text-teal-600" />{title}</h2>
        <form action={run}>
          <button className="btn btn-sm" disabled={pending}>{pending ? "Generating…" : state?.draft ? "Regenerate" : buttonLabel}</button>
        </form>
      </div>
      <div className="p-4">
        <p className="text-xs text-slate-500">{description}</p>
        {state?.error && <p role="alert" className="mt-2 text-xs text-red-700">{state.error}</p>}
        {state?.draft && <DraftEditor key={state.at} initial={state.draft} provider={state.provider ?? ""} />}
      </div>
    </section>
  );
}

function DraftEditor({ initial, provider }: { initial: string; provider: string }) {
  const [text, setText] = useState(initial);
  const [copied, setCopied] = useState(false);
  if (!text) return null;
  return (
    <div className="mt-3">
      <div className="mb-1 flex flex-wrap items-center gap-2 text-[11px]">
        <span className="rounded bg-amber-100 px-1.5 py-0.5 font-semibold text-amber-800">DRAFT – review before use</span>
        <span className="text-slate-500">Generated by {provider}. Figures come from MNT Flow records; nothing has been sent.</span>
      </div>
      <textarea value={text} onChange={(e) => setText(e.target.value)} rows={12} className="input font-mono text-xs" aria-label="Editable draft" />
      <div className="mt-2 flex gap-2">
        <button
          type="button"
          className="btn btn-sm"
          onClick={async () => {
            await navigator.clipboard.writeText(text);
            setCopied(true);
            setTimeout(() => setCopied(false), 1500);
          }}
        >
          {copied ? "Copied" : "Copy to clipboard"}
        </button>
        <button type="button" className="btn btn-sm" onClick={() => setText("")}>Discard</button>
      </div>
    </div>
  );
}

/** Suggests issue categories from the description textarea and lets the user apply one to the category select. */
export function CategorySuggest({ textareaId, selectId }: { textareaId: string; selectId: string }) {
  const [res, setRes] = useState<Awaited<ReturnType<typeof aiSuggestCategories>> | null>(null);
  const [busy, setBusy] = useState(false);
  return (
    <div className="text-xs">
      <button
        type="button"
        className="btn btn-sm"
        disabled={busy}
        onClick={async () => {
          setBusy(true);
          const notes = (document.getElementById(textareaId) as HTMLTextAreaElement | null)?.value ?? "";
          setRes(await aiSuggestCategories(notes));
          setBusy(false);
        }}
      >
        <Sparkles className="h-3.5 w-3.5 text-teal-600" /> Suggest category
      </button>
      {res && "error" in res && <span className="ml-2 text-red-700">{res.error}</span>}
      {res && "suggestions" in res && (
        <div className="mt-1.5 flex flex-wrap items-center gap-1.5">
          {res.suggestions.length === 0 && <span className="text-slate-500">No confident suggestion; choose manually.</span>}
          {res.suggestions.map((s) => (
            <button
              key={s.category}
              type="button"
              className="rounded border border-teal-200 bg-teal-50 px-2 py-0.5 text-teal-800 hover:bg-teal-100"
              title={`Matched: ${s.matched.join(", ")}`}
              onClick={() => {
                const sel = document.getElementById(selectId) as HTMLSelectElement | null;
                if (sel) sel.value = s.category;
              }}
            >
              {s.label}
            </button>
          ))}
          <span className="text-slate-400">({res.provider}; you choose)</span>
        </div>
      )}
    </div>
  );
}
